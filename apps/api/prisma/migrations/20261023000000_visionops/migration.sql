-- Tacksharp VisionOps: CCTV camera health and downtime monitoring.
-- ADDITIVE ONLY: new tables, no existing table or column changes. Idempotent (IF NOT EXISTS).
-- No camera passwords or RTSP URLs are stored: they stay on the site's local monitoring agent.
-- Back up first:  mysqldump <db> > backup.sql   then:  npx prisma migrate deploy

CREATE TABLE IF NOT EXISTS `MonitoringCustomer` (
    `id` VARCHAR(191) NOT NULL,
    `organizationId` VARCHAR(191) NOT NULL,
    `name` VARCHAR(191) NOT NULL,
    `industry` VARCHAR(191) NOT NULL DEFAULT 'other',
    `region` VARCHAR(191) NULL,
    `contactName` VARCHAR(191) NULL,
    `contactPhone` VARCHAR(191) NULL,
    `notifyOnResolution` BOOLEAN NOT NULL DEFAULT false,
    `isDemo` BOOLEAN NOT NULL DEFAULT false,
    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updatedAt` DATETIME(3) NOT NULL,
    UNIQUE INDEX `MonitoringCustomer_organizationId_name_key`(`organizationId`, `name`),
    PRIMARY KEY (`id`),
    CONSTRAINT `MonitoringCustomer_organizationId_fkey` FOREIGN KEY (`organizationId`) REFERENCES `Organization`(`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

